// F2 (#56) acceptance through the real UI: repositories, sources and policies
// against the real-component stack (e2e/stack.ts: Compose deployment, MySQL
// 8.4.11 + PXB 8.4.0-7, plain and explicit-TLS Pure-FTPd 1.0.54) driven by
// agent-browser. Every assertion reads observable state: rendered text, the
// browser URL, and the same server's API.
//
//   bun e2e/f2.ts [--evidence DIR] [--image TAG] [--headed]
//
// Screenshots and manifest.json go to DIR (default <repo>/.cache/e2e-f2/<commit>).
// On an arm64 Mac the stack runs under amd64 emulation: development evidence
// only; binding acceptance is native linux/amd64.
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { z } from "zod";
import {
  zErrorResponse,
  zPreflightResult,
  zSource,
} from "../lib/api/generated/zod.gen";
import { startStack } from "./stack";

const repo = path.resolve(import.meta.dir, "../../../..");
const args = process.argv.slice(2);
const headed = args.includes("--headed");
const evidenceArg = args.indexOf("--evidence");
const imageArg = args.indexOf("--image");
const commit =
  spawnSync("git", ["rev-parse", "--short=12", "HEAD"], {
    cwd: repo,
    encoding: "utf8",
  }).stdout.trim() || "unknown";
const dirty =
  spawnSync("git", ["status", "--porcelain"], {
    cwd: repo,
    encoding: "utf8",
  }).stdout.trim() !== "";
const evidence =
  evidenceArg >= 0
    ? path.resolve(args[evidenceArg + 1])
    : path.join(repo, ".cache/e2e-f2", commit);

type Step = {
  id: string;
  acceptance: string;
  description: string;
  screenshot?: string;
};
const steps: Step[] = [];

function expect(condition: boolean, message: string): void {
  if (!condition) {
    throw new Error(`f2 e2e: ${message}`);
  }
}

const session = `intern-f2-e2e-${process.pid}`;

function ab(...command: string[]): string {
  const result = spawnSync(
    "agent-browser",
    ["--session", session, ...(headed ? ["--headed"] : []), ...command],
    { encoding: "utf8", timeout: 120_000 },
  );
  if (result.status !== 0) {
    throw new Error(
      `agent-browser ${command[0]} failed: ${(result.stderr || result.stdout).trim()}`,
    );
  }
  return result.stdout.trim();
}

function open(url: string): void {
  // The stack serves HTTPS with a certificate this run generated; the browser
  // is told to accept exactly this one origin's certificate errors.
  ab("--ignore-https-errors", "open", url);
}

function shot(name: string): string {
  const file = path.join(evidence, `${name}.png`);
  ab(
    "wait",
    "--fn",
    "document.getAnimations().every((a) => a.playState !== 'running')",
  );
  ab("screenshot", file);
  return path.basename(file);
}

function record(step: Step): void {
  steps.push(step);
  console.log(`pass ${step.id} (${step.acceptance}): ${step.description}`);
}

function fill(label: string, value: string): void {
  ab("find", "label", label, "fill", value);
}

function click(name: string, role = "button"): void {
  ab("find", "role", role, "click", "--name", name);
}

function signOut(): void {
  ab("find", "role", "button", "click", "--name", "账户菜单");
  ab("wait", "--text", "退出登录");
  ab("find", "role", "menuitem", "click", "--name", "退出登录");
  ab("wait", "--url", "**/login**");
}

function bodyText(): string {
  return ab("get", "text", "body");
}

// --------------------------------------------------------------- API ---

/** One HTTP call against the stack; TLS verification is disabled for this run's own certificate. */
export type ApiClient = (
  method: string,
  route: string,
  cookie: string | undefined,
  body?: unknown,
) => Promise<{ status: number; json: unknown; cookie?: string }>;

function makeApi(origin: string): ApiClient {
  return async function api(method, route, cookie, body) {
    const response = await fetch(`${origin}${route}`, {
      method,
      headers: {
        ...(cookie === undefined ? {} : { Cookie: cookie }),
        ...(body === undefined ? {} : { "Content-Type": "application/json" }),
      },
      body: body === undefined ? undefined : JSON.stringify(body),
      // The certificate is generated by this run; only this origin is exempt.
      tls: { rejectUnauthorized: false },
    } as RequestInit);
    const text = await response.text();
    const setCookie = response.headers
      .getSetCookie()
      .find((value) => value.startsWith("intern_session="))
      ?.split(";")[0];
    return {
      status: response.status,
      json: text === "" ? undefined : JSON.parse(text),
      cookie: setCookie,
    };
  };
}

async function login(
  api: ApiClient,
  username: string,
  password: string,
): Promise<string> {
  const result = await api("POST", "/api/v1/auth/login", undefined, {
    username,
    password,
  });
  expect(
    result.status === 200 && result.cookie !== undefined,
    `API login ${username} = ${result.status}`,
  );
  return result.cookie as string;
}

async function createUser(
  api: ApiClient,
  adminCookie: string,
  username: string,
  password: string,
  role: "admin" | "operator" | "viewer",
): Promise<void> {
  const result = await api("POST", "/api/v1/users", adminCookie, {
    username,
    password,
    role,
  });
  expect(
    result.status === 201,
    `create ${role} = ${result.status} ${JSON.stringify(result.json)}`,
  );
}

const password = (prefix: string) =>
  `${prefix}-${Math.random().toString(36).slice(2, 12)}`;

async function main(): Promise<void> {
  mkdirSync(evidence, { recursive: true });
  const stack = await startStack(
    imageArg >= 0 ? { reuseImage: args[imageArg + 1] } : undefined,
  );
  console.log(`stack up: ${stack.origin} (${Math.round(process.uptime())}s)`);
  const api = makeApi(stack.origin);
  const adminCookie = await login(
    api,
    stack.admin.username,
    stack.admin.password,
  );
  const operator = { username: "f2-operator", password: password("operator") };
  const viewer = { username: "f2-viewer", password: password("viewer") };
  await createUser(
    api,
    adminCookie,
    operator.username,
    operator.password,
    "operator",
  );
  await createUser(
    api,
    adminCookie,
    viewer.username,
    viewer.password,
    "viewer",
  );

  try {
    // --- F2-A2: plain FTP is an explicit choice and is flagged everywhere ---
    open(`${stack.origin}/login`);
    ab("wait", "--text", "使用 Intern 账号登录控制台");
    fill("用户名", stack.admin.username);
    fill("密码", stack.admin.password);
    click("登录");
    ab("wait", "--text", "有效权限");

    open(`${stack.origin}/repositories/new`);
    ab("wait", "--text", "新建仓库");
    fill("名称", "f2-plain-ftp");
    click("FTP / FTPS", "radio");
    click("创建仓库");
    ab("wait", "--text", "请选择 FTP 传输方式");
    const tlsRequests = await api("GET", "/api/v1/repositories", adminCookie);
    expect(
      !JSON.stringify(tlsRequests.json).includes("f2-plain-ftp"),
      "a repository without an explicit TLS choice reached the server",
    );
    click("明文 FTP", "radio");
    ab("wait", "--text", "凭据与数据明文传输");
    fill("主机", stack.ftp.host);
    fill("端口", String(stack.ftp.port));
    fill("基础路径", stack.ftp.basePath);
    fill("用户名", stack.ftp.username);
    fill("密码", stack.ftp.password);
    record({
      id: "01-plain-ftp-form",
      acceptance: "F2-A2",
      description:
        "FTP repository cannot be saved without an explicit TLS choice, and choosing plain FTP shows the permanent warning",
      screenshot: shot("01-plain-ftp-form"),
    });
    click("创建仓库");
    ab("wait", "--text", "仓库已创建");
    const repositories = z
      .object({
        items: z.array(
          z.object({
            id: z.string(),
            name: z.string(),
            kind: z.string(),
            tls_mode: z.string(),
            has_secret: z.boolean(),
            plaintext_credentials: z.boolean(),
          }),
        ),
      })
      .parse((await api("GET", "/api/v1/repositories", adminCookie)).json);
    const plainRepository = repositories.items.find(
      (item) => item.name === "f2-plain-ftp",
    );
    if (plainRepository === undefined) {
      throw new Error("f2 e2e: plain FTP repository was not created");
    }
    expect(
      plainRepository.tls_mode === "plain" &&
        plainRepository.plaintext_credentials === true &&
        plainRepository.has_secret === true,
      `plain FTP repository stored as ${JSON.stringify(plainRepository)}`,
    );
    expect(
      !JSON.stringify(repositories).includes(stack.ftp.password),
      "the repository API echoed the stored password",
    );
    open(`${stack.origin}/repositories/detail?id=${plainRepository.id}`);
    ab("wait", "--text", "写入性探测");
    expect(
      bodyText().includes("凭据与数据明文传输"),
      "detail page lacks the plaintext warning",
    );
    click("运行探测");
    ab("wait", "--text", "探测通过");
    record({
      id: "02-plain-ftp-detail",
      acceptance: "F2-A2",
      description:
        "plain FTP repository detail keeps the plaintext warning, never shows the password, and probes successfully",
      screenshot: shot("02-plain-ftp-detail"),
    });

    // --- F2-A1: write-only secrets and a real preflight ---
    const local = await api("POST", "/api/v1/repositories", adminCookie, {
      name: "f2-local",
      kind: "local",
      tls_mode: "none",
      root: stack.localRepositoryRoot,
    });
    expect(local.status === 201, `create local repository = ${local.status}`);

    open(`${stack.origin}/sources/new`);
    ab("wait", "--text", "新建数据源");
    fill("名称", "f2-source");
    fill("Socket", stack.mysql.socket);
    fill("Datadir", stack.mysql.datadir);
    fill("用户名", stack.mysql.username);
    fill("密码", stack.mysql.password);
    click("创建数据源");
    ab("wait", "--text", "数据源已创建");
    const sources = z
      .object({ items: z.array(zSource) })
      .parse((await api("GET", "/api/v1/sources", adminCookie)).json);
    const source = sources.items.find((item) => item.name === "f2-source");
    if (source === undefined) {
      throw new Error("f2 e2e: source was not created");
    }
    expect(source?.has_secret === true, "source was not stored with a secret");
    expect(
      !JSON.stringify(sources).includes(stack.mysql.password),
      "the source API echoed the stored password",
    );

    open(`${stack.origin}/sources/detail?id=${source.id}`);
    ab("wait", "--text", "运行预检");
    click("运行预检");
    ab("wait", "--text", "本次预检结果");
    ab("wait", "--text", "检查项");
    const preflightText = bodyText();
    for (const check of [
      "identity",
      "compatibility",
      "volume",
      "mount",
      "privileges",
      "capacity",
    ]) {
      expect(
        preflightText.includes(check),
        `preflight output lacks the ${check} check`,
      );
    }
    expect(
      !preflightText.includes("未通过"),
      "a passing preflight rendered the failure badge",
    );
    record({
      id: "03-preflight-real",
      acceptance: "F2-A3",
      description:
        "preflight against the real MySQL 8.4.11 + PXB pair lists every check and passes",
      screenshot: shot("03-preflight-real"),
    });

    open(`${stack.origin}/sources/detail?id=${source.id}`);
    ab("wait", "--text", "编辑");
    click("编辑");
    ab("wait", "--text", "保存修改");
    const passwordValue = ab("get", "attr", "#source-password", "value");
    expect(
      passwordValue === "",
      `the edit form pre-filled the password (${passwordValue})`,
    );
    fill("名称", "f2-source-renamed");
    click("保存修改");
    ab("wait", "--text", "数据源已更新");
    const afterRename = z
      .object({ items: z.array(zSource) })
      .parse((await api("GET", "/api/v1/sources", adminCookie)).json);
    const renamed = afterRename.items.find((item) => item.id === source.id);
    expect(
      renamed !== undefined &&
        renamed.name === "f2-source-renamed" &&
        renamed.has_secret,
      "renaming without a password dropped or replaced the stored secret",
    );
    const rePreflight = await api(
      "POST",
      `/api/v1/sources/${source.id}/preflight`,
      adminCookie,
      {
        local_repository_id:
          (local.json as { repository?: { id: string }; id?: string })
            .repository?.id ?? (local.json as { id: string }).id,
      },
    );
    expect(
      rePreflight.status === 200 &&
        (rePreflight.json as { ok?: boolean }).ok === true,
      `preflight after the password-preserving update = ${rePreflight.status} ${JSON.stringify(rePreflight.json)}`,
    );
    record({
      id: "04-write-only-secret",
      acceptance: "F2-A1",
      description:
        "the edit form never renders the stored password, and saving without it keeps the secret usable (preflight still passes)",
      screenshot: shot("04-write-only-secret"),
    });

    // --- F2-A3: a failing preflight is shown and writes nothing ---
    const badSource = await api("POST", "/api/v1/sources", adminCookie, {
      name: "f2-bad-source",
      socket: stack.mysql.socket,
      datadir: stack.mysql.datadir,
      username: stack.mysql.username,
      password: "wrong-password-for-f2",
    });
    expect(badSource.status === 201, `create bad source = ${badSource.status}`);
    const badSourceId = (badSource.json as { id: string }).id;
    const failedPreflight = await api(
      "POST",
      `/api/v1/sources/${badSourceId}/preflight`,
      adminCookie,
      {
        local_repository_id: (local.json as { id: string }).id,
      },
    );
    expect(
      failedPreflight.status === 200,
      `bad preflight status ${failedPreflight.status}`,
    );
    const failedResult = zPreflightResult.parse(failedPreflight.json);
    expect(!failedResult.ok, "a wrong password produced a passing preflight");
    open(`${stack.origin}/sources/detail?id=${badSourceId}`);
    ab("wait", "--text", "运行预检");
    click("运行预检");
    ab("wait", "--text", "本次预检结果");
    ab("wait", "--text", "未通过");
    // The page must render what the backend reported: the failing check or
    // error code, not just a generic failure.
    const failing = [
      failedResult.error?.check,
      failedResult.error?.code,
    ].filter(
      (value): value is string => typeof value === "string" && value !== "",
    );
    const failureText = bodyText();
    expect(
      failing.length > 0,
      `the backend reported no failing check: ${JSON.stringify(failedResult)}`,
    );
    for (const name of failing) {
      expect(
        failureText.includes(name),
        `the page does not show the failing check ${name}; backend ${JSON.stringify(failedResult)}; page: ${failureText.slice(0, 1200)}`,
      );
    }
    record({
      id: "05-preflight-failed",
      acceptance: "F2-A3",
      description:
        "a source with a wrong password fails preflight and the page shows the structured failure",
      screenshot: shot("05-preflight-failed"),
    });

    // --- F2-A4: enable and update failures keep the stored policy state ---
    const localId = (local.json as { id: string }).id;
    const policyBody = {
      name: "f2-policy-bad",
      source_id: badSourceId,
      local_repository_id: localId,
      replica_repository_id: null,
      full_cron: "0 2 * * *",
      incremental_cron: "0 * * * *",
      timezone: "Asia/Shanghai",
      max_chain_length: 7,
      parallel: 1,
      throttle: 0,
      zstd_level: 3,
      page_tracking: false,
      enabled: false,
    };
    const badPolicy = await api(
      "POST",
      "/api/v1/policies",
      adminCookie,
      policyBody,
    );
    expect(badPolicy.status === 201, `create policy = ${badPolicy.status}`);
    const badPolicyId = (badPolicy.json as { id: string }).id;
    open(`${stack.origin}/policies/detail?id=${badPolicyId}`);
    ab("wait", "--text", "未启用");
    click("启用");
    ab("wait", "--text", "启用失败");
    const stillDisabled = await api(
      "GET",
      `/api/v1/policies/${badPolicyId}`,
      adminCookie,
    );
    expect(
      (stillDisabled.json as { enabled?: boolean }).enabled === false,
      "a policy whose enable preflight failed became enabled",
    );
    record({
      id: "06-enable-refused",
      acceptance: "F2-A4",
      description:
        "enabling a policy whose source preflight fails shows the outcome and leaves it disabled",
      screenshot: shot("06-enable-refused"),
    });

    const goodPolicy = await api("POST", "/api/v1/policies", adminCookie, {
      ...policyBody,
      name: "f2-policy-good",
      source_id: source.id,
    });
    expect(
      goodPolicy.status === 201,
      `create good policy = ${goodPolicy.status}`,
    );
    const goodPolicyId = (goodPolicy.json as { id: string }).id;
    const enabled = await api(
      "POST",
      `/api/v1/policies/${goodPolicyId}/enable`,
      adminCookie,
    );
    expect(enabled.status === 200, `enable good policy = ${enabled.status}`);
    open(`${stack.origin}/policies/detail?id=${goodPolicyId}`);
    ab("wait", "--text", "已启用");
    click("编辑");
    ab("wait", "--text", "保存修改");
    ab("find", "role", "combobox", "click", "--name", "数据源");
    ab("wait", "--text", "f2-bad-source");
    ab("find", "role", "option", "click", "--name", "f2-bad-source");
    fill("全量 cron", "5 3 * * *");
    click("保存修改");
    ab("wait", "--text", "保存被预检拒绝");
    const afterFailedUpdate = await api(
      "GET",
      `/api/v1/policies/${goodPolicyId}`,
      adminCookie,
    );
    const updated = afterFailedUpdate.json as {
      enabled?: boolean;
      full_cron?: string;
      source_id?: string;
    };
    expect(
      updated.enabled === true &&
        updated.full_cron === "0 2 * * *" &&
        updated.source_id === source.id,
      `a rejected update changed the policy: ${JSON.stringify(updated)}`,
    );
    record({
      id: "07-update-refused",
      acceptance: "F2-A4",
      description:
        "a rejected update of an enabled policy keeps it enabled with its original source and cron",
      screenshot: shot("07-update-refused"),
    });

    // --- F2-A5: role-based visibility ---
    ab("find", "role", "button", "click", "--name", "账户菜单");
    ab("wait", "--text", "退出登录");
    ab("find", "role", "menuitem", "click", "--name", "退出登录");
    ab("wait", "--url", "**/login**");
    fill("用户名", viewer.username);
    fill("密码", viewer.password);
    click("登录");
    ab("wait", "--text", "有效权限");
    open(`${stack.origin}/repositories`);
    ab("wait", "--text", "备份仓库");
    expect(
      !bodyText().includes("新建仓库"),
      "a viewer sees the create-repository action",
    );
    open(`${stack.origin}/repositories/new`);
    ab("wait", "--text", "没有权限");
    const viewerWrite = await api(
      "POST",
      "/api/v1/repositories",
      await login(api, viewer.username, viewer.password),
      {
        name: "viewer-should-fail",
        kind: "local",
        tls_mode: "none",
        root: stack.localRepositoryRoot,
      },
    );
    expect(viewerWrite.status === 403, `viewer write = ${viewerWrite.status}`);
    record({
      id: "08-viewer-read-only",
      acceptance: "F2-A5",
      description:
        "a viewer has no write actions, the create page refuses, and the API answers 403",
      screenshot: shot("08-viewer-read-only"),
    });

    // The login page sends a signed-in visitor straight to the console, so the
    // viewer session is closed before the next sign-in.
    signOut();
    ab("wait", "--text", "使用 Intern 账号登录控制台");
    fill("用户名", operator.username);
    fill("密码", operator.password);
    click("登录");
    ab("wait", "--text", "有效权限");
    open(`${stack.origin}/repositories/new`);
    ab("wait", "--text", "没有权限");
    open(`${stack.origin}/sources/new`);
    ab("wait", "--text", "新建数据源");
    const operatorRepository = await api(
      "POST",
      "/api/v1/repositories",
      await login(api, operator.username, operator.password),
      {
        name: "operator-should-fail",
        kind: "local",
        tls_mode: "none",
        root: stack.localRepositoryRoot,
      },
    );
    expect(
      operatorRepository.status === 403,
      `operator repository write = ${operatorRepository.status}`,
    );
    record({
      id: "09-operator-scope",
      acceptance: "F2-A5",
      description:
        "an operator can open the source form but not manage repositories",
      screenshot: shot("09-operator-scope"),
    });

    // --- F2-A6: an unconfigured deployment explains itself ---
    if (stack.noKek === undefined) {
      throw new Error(
        "f2 e2e: the stack did not provide a KEK-less deployment",
      );
    }
    const noKekApi = makeApi(stack.noKek.origin);
    await login(
      noKekApi,
      stack.noKek.admin.username,
      stack.noKek.admin.password,
    );
    open(`${stack.noKek.origin}/login`);
    ab("wait", "--text", "使用 Intern 账号登录控制台");
    fill("用户名", stack.noKek.admin.username);
    fill("密码", stack.noKek.admin.password);
    click("登录");
    ab("wait", "--text", "有效权限");
    open(`${stack.noKek.origin}/sources/new`);
    ab("wait", "--text", "新建数据源");
    fill("名称", "no-kek-source");
    fill("Socket", stack.mysql.socket);
    fill("Datadir", stack.mysql.datadir);
    fill("用户名", stack.mysql.username);
    fill("密码", stack.mysql.password);
    click("创建数据源");
    ab("wait", "--text", "当前部署缺少完成此操作所需的配置");
    const noKekResponse = await api("POST", "/api/v1/sources", undefined, {});
    expect(
      noKekResponse.status === 401,
      "the KEK-less API answered an unauthenticated write",
    );
    record({
      id: "10-no-kek",
      acceptance: "F2-A6",
      description:
        "without a KEK the create form reports the missing deployment configuration instead of an unhandled error",
      screenshot: shot("10-no-kek"),
    });

    // The API contract of the failure the page rendered above.
    const noKekCookie = await login(
      noKekApi,
      stack.noKek.admin.username,
      stack.noKek.admin.password,
    );
    const unavailable = await noKekApi("POST", "/api/v1/sources", noKekCookie, {
      name: "no-kek-source",
      socket: stack.mysql.socket,
      datadir: stack.mysql.datadir,
      username: stack.mysql.username,
      password: stack.mysql.password,
    });
    const error = zErrorResponse.parse(unavailable.json);
    expect(
      unavailable.status === 503 && error.error.code === "unavailable",
      `KEK-less source create = ${unavailable.status} ${error.error.code}`,
    );

    const errors = ab("errors");
    expect(errors === "", `page errors: ${errors}`);
    const consoleOutput = ab("console");
    expect(
      !/Content Security Policy|Refused to/i.test(consoleOutput),
      `CSP violations: ${consoleOutput}`,
    );
    record({
      id: "11-clean-console",
      acceptance: "F2-A2",
      description: "no page errors or CSP violations",
    });
  } finally {
    spawnSync("agent-browser", ["--session", session, "close"], {
      encoding: "utf8",
    });
    await stack.stop();
  }
}

try {
  await main();
  writeFileSync(
    path.join(evidence, "manifest.json"),
    `${JSON.stringify({ commit, dirty, steps }, null, 2)}\n`,
  );
  console.log(
    `f2 e2e: ${steps.length} steps passed; evidence in ${evidence}${dirty ? " (working tree dirty)" : ""}`,
  );
} catch (error) {
  spawnSync("agent-browser", ["--session", session, "close"], {
    encoding: "utf8",
  });
  throw error;
}
