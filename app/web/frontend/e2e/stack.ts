/** A running real-component stack. All paths are as seen inside the intern container. */
export type Stack = {
  /** HTTPS origin of the intern service, e.g. https://127.0.0.1:49152. */
  origin: string;
  /** The first administrator created through the container binary. */
  admin: { username: string; password: string };
  /** Values an operator types into the source form. */
  mysql: {
    socket: string;
    datadir: string;
    username: string;
    password: string;
  };
  /** Plain FTP reachable from the intern container. */
  ftp: {
    host: string;
    port: number;
    username: string;
    password: string;
    basePath: string;
  };
  /** Explicit FTPS reachable from the intern container, with its public CA bundle. */
  ftps?: {
    host: string;
    port: number;
    username: string;
    password: string;
    basePath: string;
    tlsMode: "explicit" | "implicit";
    caBundlePem: string;
  };
  /** Absolute path inside the container usable as a local repository root. */
  localRepositoryRoot: string;
  /** A second intern container on the same image without a KEK, or undefined. */
  noKek:
    | { origin: string; admin: { username: string; password: string } }
    | undefined;
  /**
   * Takes the plain FTP server off the Compose network (`down`) or back (`up`):
   * a real outage for replica failure and retry scenarios, not a simulated error.
   */
  setFtp(state: "down" | "up"): void;
  /** Removes every container, volume, network and temporary file this stack created. */
  stop(): Promise<void>;
};

export type StackOptions = {
  /** A linux/amd64 image already built from app/web/deploy/Dockerfile. Skips the build. */
  reuseImage?: string;
};

