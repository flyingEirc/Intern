function portOfComposeService(
  compose: (args: string[]) => ExecResult,
  service: string,
  privatePort: string,
): string {
  const out = compose(["port", service, privatePort]).stdout.trim();
  const match = out.match(/:(\d+)$/);
  if (!match)
    throw new Error(
      `docker compose port ${service} ${privatePort} returned ${JSON.stringify(out)}`,
    );
  return match[1];
}

function portOfContainer(name: string, privatePort: string): string {
  const out = docker(`port of ${name}`, [
    "port",
    name,
    `${privatePort}/tcp`,
  ]).stdout.trim();
  const match = out.match(/:(\d+)$/);
  if (!match)
    throw new Error(
      `docker port ${name} ${privatePort}/tcp returned ${JSON.stringify(out)}`,
    );
  return match[1];
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

/**
 * Start the stack. On any failure the partially created containers, volumes,
 * network and temporary directory are removed before the error is rethrown.
 */
export async function startStack(options: StackOptions = {}): Promise<Stack> {
  requirePrerequisites();
  const rawPlatform = exec([
    "docker",
    "info",
    "--format",
    "{{.OSType}}/{{.Architecture}}",
  ]).stdout.trim();
  const [osType, rawArch] = rawPlatform.split("/");
  const hostArch =
    { x86_64: "amd64", amd64: "amd64", aarch64: "arm64", arm64: "arm64" }[
      rawArch
    ] ?? rawArch;
  if (!osType || !hostArch) {
    throw new Error(`docker reported platform ${JSON.stringify(rawPlatform)}`);
  }
  const hostPlatform = `${osType}/${hostArch}`;
  const compat = compatibility();
  const sourceSha = git(["rev-parse", "HEAD"]);
  const dirty = git(["status", "--porcelain"]) !== "";
  const shortSha = sourceSha.slice(0, 12);
  const tagComponent = `e2e-${shortSha}${dirty ? "-dirty" : ""}`;
  const builtImage = `intern:${tagComponent}-mysql8.4`;
  const image = options.reuseImage ?? builtImage;

  const root = mkdtempSync(path.join(tmpdir(), "intern-e2e-stack-"));
  const secretsDir = path.join(root, "secrets");
  const exportDir = path.join(root, "export");
  const overrideFile = path.join(root, "override.yaml");
  const envFile = path.join(root, "stack.env");
  const plainPasswordFile = path.join(root, "ftp-password");
  const ftpsPasswordFile = path.join(root, "ftps-password");
  mkdirSync(secretsDir, { recursive: true, mode: 0o700 });
  // The reference deployment bind-mounts this directory. It is created so
  // exportsHostDir names a real path, but the container mounts the named
  // export volume instead: an OrbStack bind mount stays root-owned.
  mkdirSync(exportDir, { recursive: true, mode: 0o750 });

  // On a GitHub runner (RUNNER_NAME set) the project name carries the first 8
  // hex digits of sha256(RUNNER_NAME): runners sharing one Docker engine then
  // never remove each other's stacks, and e2e-stack-clean.sh can still remove
  // this runner's leftovers when a cancelled job never reached cleanup().
  const runner = process.env.RUNNER_NAME;
  const runnerScope = runner
    ? `${createHash("sha256").update(runner).digest("hex").slice(0, 8)}-`
    : "";
  const project = `intern-e2e-${runnerScope}${randomBytes(4).toString("hex")}`;
  const secretsVolume = `${project}-secrets`;
  const ftpVolume = `${project}-ftp-data`;
  const ftpsVolume = `${project}-ftps-data`;
  const noKekName = `${project}-nokek`;
  const noKekVolume = `${project}-nokek-metadata`;
  const exportVolume = `${project}-export`;
  const volumes = [
    secretsVolume,
    ftpVolume,
    ftpsVolume,
    noKekVolume,
    exportVolume,
  ];

  const mysqlRootPassword = randomSecret();
  const postgresPassword = randomSecret();
  const backupPassword = randomSecret();
  const admin = { username: "e2e-admin", password: randomSecret() };
  const ftpPassword = randomSecret();
  const ftpsPassword = randomSecret();
  const noKekAdmin = { username: "e2e-nokek-admin", password: randomSecret() };

  const compose = (args: string[], execOptions: ExecOptions = {}): ExecResult =>
    exec(
      [
        "docker",
        "compose",
        "--project-name",
        project,
        "--file",
        composeFile,
        "--file",
        overrideFile,
        "--env-file",
        envFile,
        ...args,
      ],
      execOptions,
    );
  const composeMust = (
    label: string,
    args: string[],
    execOptions: ExecOptions = {},
  ): ExecResult => {
    const result = compose(args, execOptions);
    if (result.code !== 0) {
      throw new Error(
        `${label} failed (exit ${result.code}): docker compose ${args.join(" ")}\n${tail(result.stdout + result.stderr)}`,
      );
    }
    return result;
  };

  let cleaned = false;
  const cleanup = async (): Promise<void> => {
    if (cleaned) return;
    cleaned = true;
    const failures: string[] = [];
    const attempt = (
      label: string,
      action: () => ExecResult,
      absent?: RegExp,
    ): void => {
      try {
        const result = action();
        const output = result.stdout + result.stderr;
        if (result.code !== 0 && !absent?.test(output)) {
          failures.push(`${label}: ${tail(output, 800)}`);
        }
      } catch (error) {
        failures.push(`${label}: ${String(error)}`);
      }
    };
    attempt(
      "remove no-KEK container",
      () => exec(["docker", "rm", "--force", "--volumes", noKekName]),
      /no such container/i,
    );
    const exported = exec([
      "docker",
      "ps",
      "--all",
      "--quiet",
      "--filter",
      `label=io.intern.e2e.export=${project}`,
    ])
      .stdout.split("\n")
      .map((id) => id.trim())
      .filter(Boolean);
    for (const id of exported) {
      attempt(
        `remove exported MySQL ${id}`,
        () => exec(["docker", "rm", "--force", id]),
        /no such container/i,
      );
    }
    if (existsSync(overrideFile) && existsSync(envFile)) {
      attempt("compose down", () =>
        compose(["down", "--volumes", "--remove-orphans", "--timeout", "120"]),
      );
    }
    for (const volume of volumes) {
      attempt(
        `remove volume ${volume}`,
        () => exec(["docker", "volume", "rm", "--force", volume]),
        /no such volume|not found/i,
      );
    }
    try {
      rmSync(root, { recursive: true, force: true });
    } catch (error) {
      failures.push(`remove temporary directory: ${String(error)}`);
    }
    if (failures.length > 0) {
      throw new Error(`stack cleanup failed:\n${failures.join("\n")}`);
    }
  };

  try {
    // ------------------------------------------------------------- secrets ---
    const cli = ensureCli();
    const kekPath = path.join(secretsDir, "intern_kek");
    must("generate KEK", [cli, "keygen", "--key-file", kekPath], { cwd: repo });
    chmodSync(kekPath, 0o600);
    generateTls(secretsDir, compat.mysql_image);
    writeFileSync(
      path.join(secretsDir, "intern_postgres_password"),
      `${postgresPassword}\n`,
      { mode: 0o600 },
    );
    writeFileSync(
      path.join(secretsDir, "intern_database_url"),
      `postgres://intern:${encodeURIComponent(postgresPassword)}@postgres:5432/intern?sslmode=disable\n`,
      { mode: 0o600 },
    );
    writeFileSync(
      path.join(secretsDir, "intern_nokek_database_url"),
      `postgres://intern:${encodeURIComponent(postgresPassword)}@postgres:5432/intern_nokek?sslmode=disable\n`,
      { mode: 0o600 },
    );

    writeFileSync(plainPasswordFile, `${ftpPassword}\n${ftpPassword}\n`, {
      mode: 0o600,
    });
    writeFileSync(ftpsPasswordFile, `${ftpsPassword}\n${ftpsPassword}\n`, {
      mode: 0o600,
    });

    // ------------------------------------------------------------- fixtures ---
    const plainImage = buildFixture(
      "build plain FTP fixture",
      plainFixtureDockerfile,
      plainFixtureImage,
      path.dirname(plainFixtureDockerfile),
      hostPlatform,
    );
    const ftpsImage = buildFixture(
      "build FTPS fixture",
      ftpsFixtureDockerfile,
      ftpsFixtureImage,
      path.dirname(ftpsFixtureDockerfile),
      hostPlatform,
    );

    // ---------------------------------------------------------------- image ---
    if (options.reuseImage) {
      if (!imageExists(options.reuseImage)) {
        throw new Error(
          `reuseImage ${options.reuseImage} does not exist locally`,
        );
      }
      const inspected = docker("inspect reuseImage", [
        "image",
        "inspect",
        "--format",
        "{{.Os}}/{{.Architecture}}",
        options.reuseImage,
      ]).stdout.trim();
      if (inspected !== platform) {
        throw new Error(
          `reuseImage ${options.reuseImage} is ${inspected}, want ${platform}`,
        );
      }
    } else {
      buildInternImage(builtImage, sourceSha, compat);
    }

    // ---------------------------------------------------------------- volumes ---
    prepareSecretsVolume(
      secretsVolume,
      project,
      secretsDir,
      compat.mysql_image,
    );
    prepareExportVolume(exportVolume, project, compat.mysql_image);
    createVolume("create plain FTP data volume", ftpVolume, project);
    createVolume("create FTPS data volume", ftpsVolume, project);
    // The fixtures chroot each account to its home, so the repository base path
    // is relative to that home. Pre-create it as the FTP user would.
    docker("prepare FTP data volumes", [
      "run",
      "--rm",
      "--platform",
      hostPlatform,
      "--user",
      "0:0",
      "--network",
      "none",
      "--volume",
      `${ftpVolume}:/ftp`,
      "--volume",
      `${ftpsVolume}:/ftps`,
      "--entrypoint",
      "/bin/sh",
      alpineImage,
      "-c",
      "mkdir -p /ftp/normal/backups /ftps/normal/backups && chown -R 1000:1000 /ftp /ftps",
    ]);

    // --------------------------------------------------------------- override ---
    const override = [
      "# Generated by app/web/frontend/e2e/stack.ts. Test-only Compose override:",
      "# it points the service at the uid-999 secrets volume, adds the FTP fixtures",
      "# and sizes MySQL for a laptop. It declares no deployment semantics.",
      "services:",
      "  mysql:",
      `    platform: ${platform}`,
      "    command:",
      "      - --innodb-buffer-pool-size=64M",
      "      - --innodb-redo-log-capacity=33554432",
      "  intern:",
      `    platform: ${platform}`,
      `    image: ${yamlString(image)}`,
      "    # OrbStack's cgroup v2 layout has no io.weight; the reference file's",
      "    # blkio_config would make container creation fail on a Mac. This is a",
      "    # test-only host adaptation, not a deployment change.",
      "    blkio_config: !reset null",
      "    environment:",
      "      INTERN_DATABASE_URL_FILE: /run/intern-secrets/intern_database_url",
      "      INTERN_KEK_FILE: /run/intern-secrets/intern_kek",
      "      INTERN_TLS_CERT_FILE: /run/intern-secrets/intern_tls_cert",
      "      INTERN_TLS_KEY_FILE: /run/intern-secrets/intern_tls_key",
      "    volumes:",
      '      - "intern-secrets:/run/intern-secrets:ro"',
      "      # Replaces the reference file's host bind mount. A named volume is",
      "      # the only mount whose owner OrbStack lets the container set, and",
      "      # operations.md requires uid 999 and mode 0750. Later entries win.",
      '      - "intern-export:/var/lib/intern/export"',
      "  ftp:",
      `    platform: ${hostPlatform}`,
      `    image: ${yamlString(plainImage)}`,
      '    entrypoint: ["/bin/sh", "-c", "cp /fixture/password /run/s1-password && exec /usr/local/bin/ftp-fixture"]',
      "    volumes:",
      `      - ${yamlString(`${plainPasswordFile}:/fixture/password:ro`)}`,
      '      - "ftp-data:/data"',
      "    healthcheck:",
      '      test: ["CMD-SHELL", "nc -z 127.0.0.1 2121"]',
      "      interval: 2s",
      "      timeout: 2s",
      "      retries: 30",
      "      start_period: 5s",
      "  ftps:",
      `    platform: ${hostPlatform}`,
      `    image: ${yamlString(ftpsImage)}`,
      '    entrypoint: ["/bin/sh", "-c", "cp /fixture/password /run/ftp-password && exec /usr/local/bin/ftps-fixture"]',
      "    volumes:",
      `      - ${yamlString(`${ftpsPasswordFile}:/fixture/password:ro`)}`,
      `      - ${yamlString(`${path.join(secretsDir, "ftps.pem")}:/run/tls/ftps.pem:ro`)}`,
      '      - "ftps-data:/data"',
      "    healthcheck:",
      '      test: ["CMD-SHELL", "nc -z 127.0.0.1 2121 && nc -z 127.0.0.1 990"]',
      "      interval: 2s",
      "      timeout: 2s",
      "      retries: 30",
      "      start_period: 5s",
      "volumes:",
      "  intern-secrets:",
      `    name: ${yamlString(secretsVolume)}`,
      "  intern-export:",
      `    name: ${yamlString(exportVolume)}`,
      "  ftp-data:",
      `    name: ${yamlString(ftpVolume)}`,
      "  ftps-data:",
      `    name: ${yamlString(ftpsVolume)}`,
      "",
    ].join("\n");
    writeFileSync(overrideFile, override, { mode: 0o600 });

    const env = [
      `MYSQL_ROOT_PASSWORD=${mysqlRootPassword}`,
      `INTERN_MYSQL_IMAGE=${compat.mysql_image}`,
      `INTERN_PXB_IMAGE=${compat.pxb_image}`,
      `INTERN_VERSION=${tagComponent}`,
      `INTERN_SOURCE_SHA=${sourceSha}`,
      `INTERN_POSTGRES_PASSWORD_FILE=${path.join(secretsDir, "intern_postgres_password")}`,
      `INTERN_DATABASE_URL_FILE=${path.join(secretsDir, "intern_database_url")}`,
      "INTERN_HOST_PORT=0",
      `INTERN_KEK_FILE_HOST=${path.join(secretsDir, "intern_kek")}`,
      `INTERN_TLS_CERT_HOST=${path.join(secretsDir, "intern_tls_cert")}`,
      `INTERN_TLS_KEY_HOST=${path.join(secretsDir, "intern_tls_key")}`,
      `INTERN_EXPORT_HOST_DIR=${exportDir}`,
      "INTERN_MIN_WORK_BYTES=268435456",
      "INTERN_MIN_BACKUP_BYTES=268435456",
      "INTERN_LOG_LEVEL=info",
      "COMPOSE_PROGRESS=quiet",
      "",
    ].join("\n");
    writeFileSync(envFile, env, { mode: 0o600 });

    // ----------------------------------------------------------------- start ---
    // `up --detach` returns after the containers are created. Health is then
    // read from the containers' own healthchecks, so a failure names the
    // service and includes its logs instead of a generic Compose timeout.
    composeMust("docker compose up", ["up", "--detach"], {
      timeoutMs: 10 * 60 * 1000,
    });
    const serviceContainer = (service: string): string => {
      const ids = composeMust(`container of ${service}`, ["ps", "-q", service])
        .stdout.trim()
        .split("\n")
        .filter(Boolean);
      if (ids.length !== 1)
        throw new Error(
          `service ${service} has ${ids.length} containers, want 1`,
        );
      return ids[0];
    };
    const serviceHealth = async (
      service: string,
      timeoutMs: number,
    ): Promise<void> => {
      const id = serviceContainer(service);
      await waitFor(
        `${service} health`,
        () => {
          const out = exec([
            "docker",
            "inspect",
            "--format",
            "{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}",
            id,
          ]).stdout.trim();
          const [state, health] = out.split(" ");
          if (state !== "running") {
            const logs = compose(["logs", "--tail", "60", service]);
            throw new Error(
              `${service} is ${state}:\n${tail(logs.stdout + logs.stderr)}`,
            );
          }
          return health === "healthy";
        },
        timeoutMs,
      );
    };
    await Promise.all([
      serviceHealth("mysql", 300_000),
      serviceHealth("postgres", 120_000),
      serviceHealth("ftp", 120_000),
      serviceHealth("ftps", 120_000),
      serviceHealth("intern", 300_000),
    ]);
    const port = portOfComposeService(compose, "intern", "8443");
    const origin = `https://127.0.0.1:${port}`;

    // `migrate status` is the documented readiness entry point; the service
    // healthcheck only proves the process answers /healthz.
    await waitFor(
      "intern migrate status",
      () =>
        compose(["exec", "-T", "intern", "intern-web", "migrate", "status"])
          .code === 0,
      120_000,
    );

    // --------------------------------------------------------- backup account ---
    const sql = [
      `CREATE USER IF NOT EXISTS '${backupUser}'@'localhost' IDENTIFIED BY '${backupPassword}';`,
      `GRANT BACKUP_ADMIN, PROCESS, RELOAD, LOCK TABLES, REPLICATION CLIENT ON *.* TO '${backupUser}'@'localhost';`,
      `GRANT SELECT ON performance_schema.log_status TO '${backupUser}'@'localhost';`,
      `GRANT SELECT ON performance_schema.keyring_component_status TO '${backupUser}'@'localhost';`,
      `GRANT SELECT ON performance_schema.replication_group_members TO '${backupUser}'@'localhost';`,
      "",
    ].join("\n");
    composeMust(
      "create backup account",
      [
        "exec",
        "-T",
        "mysql",
        "sh",
        "-c",
        'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysql -uroot',
      ],
      { input: sql },
    );

    // ------------------------------------------------------------- first admin ---
    if (!options.setupInBrowser) {
      const initialized = await makeApi(origin)(
        "POST",
        "/api/v1/auth/setup",
        undefined,
        admin,
      );
      if (initialized.status !== 201) {
        throw new Error(`main setup returned ${initialized.status}`);
      }
    }
    composeMust("create isolated no-KEK database", [
      "exec",
      "-T",
      "postgres",
      "createdb",
      "-U",
      "intern",
      "intern_nokek",
    ]);

    // ------------------------------------------------------- KEK-less instance ---
    createVolume("create no-KEK metadata volume", noKekVolume, project);
    docker("start no-KEK intern", [
      "run",
      "--detach",
      "--name",
      noKekName,
      "--platform",
      platform,
      "--user",
      "999:999",
      "--label",
      `${projectLabel}=${project}`,
      "--network",
      `${project}_default`,
      "--publish",
      "127.0.0.1::8443",
      "--env",
      "INTERN_LISTEN=0.0.0.0:8443",
      "--env",
      "INTERN_METADATA_DIR=/var/lib/intern/metadata",
      "--env",
      "INTERN_DATABASE_URL_FILE=/run/intern-secrets/intern_nokek_database_url",
      "--env",
      "INTERN_TLS_CERT_FILE=/run/intern-secrets/intern_tls_cert",
      "--env",
      "INTERN_TLS_KEY_FILE=/run/intern-secrets/intern_tls_key",
      "--env",
      "INTERN_LOG_LEVEL=info",
      "--volume",
      `${noKekVolume}:/var/lib/intern/metadata`,
      "--volume",
      `${secretsVolume}:/run/intern-secrets:ro`,
      image,
    ]);
    await waitFor(
      "no-KEK intern healthcheck",
      () =>
        exec(["docker", "exec", noKekName, "intern-web", "healthcheck"])
          .code === 0,
      180_000,
    );
    const noKekOrigin = `https://127.0.0.1:${portOfContainer(noKekName, "8443")}`;
    const initializedNoKek = await makeApi(noKekOrigin)(
      "POST",
      "/api/v1/auth/setup",
      undefined,
      noKekAdmin,
    );
    if (initializedNoKek.status !== 201) {
      throw new Error(`no-KEK setup returned ${initializedNoKek.status}`);
    }

    const caBundlePem = readFileSync(path.join(secretsDir, "ca.pem"), "utf8");

    // The intern process is uid 999. Its view of the export root is the
    // contract operations.md states, checked here rather than assumed.
    const exportStat = composeMust("inspect the export root", [
      "exec",
      "-T",
      "intern",
      "stat",
      "-c",
      "%u %g %a %F",
      exportRoot,
    ]).stdout.trim();
    if (exportStat !== "999 999 750 directory") {
      throw new Error(
        `intern sees ${exportRoot} as ${JSON.stringify(exportStat)}, want "999 999 750 directory"`,
      );
    }

    const mysqlClient = [
      "mysql",
      "--user=root",
      "--batch",
      "--skip-column-names",
      "--default-character-set=utf8mb4",
    ];
    const queryMysql = (sqlText: string): string => {
      const result = compose(
        ["exec", "-T", "--env", "MYSQL_PWD", "mysql", ...mysqlClient],
        {
          input: sqlText.endsWith("\n") ? sqlText : `${sqlText}\n`,
          env: { MYSQL_PWD: mysqlRootPassword },
          timeoutMs: 60_000,
        },
      );
      if (result.code !== 0) {
        throw new Error(
          `mysql failed (exit ${result.code}): ${tail(result.stdout + result.stderr)}`,
        );
      }
      return result.stdout.replace(/\n$/, "");
    };

    const backupsVolume = (): string => {
      // `docker compose volumes` exists, but it prints a table and has no
      // machine format. The project name is the volume's prefix.
      const name = docker("name the backups volume", [
        "volume",
        "ls",
        "--format",
        "{{.Name}}",
      ])
        .stdout.split("\n")
        .map((line) => line.trim())
        .find((line) => line === `${project}_intern-backups`);
      if (name === undefined) {
        throw new Error(`project ${project} has no intern-backups volume`);
      }
      return name;
    };

    const exportedServers: string[] = [];
    const removeExported = (name: string): void => {
      const result = exec(["docker", "rm", "--force", name]);
      const output = result.stdout + result.stderr;
      if (result.code !== 0 && !/no such container/i.test(output)) {
        throw new Error(
          `remove exported MySQL ${name} failed: ${tail(output)}`,
        );
      }
    };

    return {
      origin,
      admin,
      mysql: {
        socket: mysqlSocket,
        datadir: mysqlDataDir,
        username: backupUser,
        password: backupPassword,
      },
      ftp: {
        host: "ftp",
        port: 2121,
        username: "normal",
        password: ftpPassword,
        basePath: "/backups",
      },
      ftps: {
        host: "ftps",
        port: 2121,
        username: "normal",
        password: ftpsPassword,
        basePath: "/backups",
        tlsMode: "explicit",
        caBundlePem,
      },
      localRepositoryRoot,
      noKek: { origin: noKekOrigin, admin: noKekAdmin },
      setFtp: (state) => {
        // Detaching the running container from the Compose network is a real
        // outage that keeps the server's state: restarting the fixture would
        // lose its one-shot password file, so the service is not stopped.
        const container = composeMust("find the plain FTP container", [
          "ps",
          "--quiet",
          "ftp",
        ]).stdout.trim();
        const network = `${project}_default`;
        docker(
          state === "down"
            ? "detach the plain FTP server"
            : "reattach the plain FTP server",
          state === "down"
            ? ["network", "disconnect", network, container]
            : ["network", "connect", "--alias", "ftp", network, container],
        );
      },
      stop: async () => {
        for (const name of exportedServers) removeExported(name);
        await cleanup();
      },
      exportsHostDir: exportDir,
      exportVolume,
      mysqlQuery: async (sqlText) => queryMysql(sqlText),
      postgresFixtureQuery: (sqlText) =>
        composeMust("query PostgreSQL test fixture", [
          "exec",
          "-T",
          "postgres",
          "psql",
          "-X",
          "-U",
          "intern",
          "-d",
          "intern",
          "--no-align",
          "--tuples-only",
          "--set",
          "ON_ERROR_STOP=1",
          "--command",
          sqlText,
        ]).stdout.trim(),
      exportEntries: () =>
        docker(
          "list the export root",
          [
            "run",
            "--rm",
            "--platform",
            platform,
            "--user",
            "999:999",
            "--network",
            "none",
            "--volume",
            `${exportVolume}:/export:ro`,
            "--entrypoint",
            "/bin/sh",
            compat.mysql_image,
            "-c",
            "ls -A1 /export",
          ],
          { timeoutMs: 60_000 },
        )
          .stdout.split("\n")
          .filter((name) => name !== ""),
      removeLocalPayload: (objectPath) => {
        const relative = safeObjectPath(objectPath);
        // Same removal Repository.ReclaimPublished performs: the published
        // directory and nothing else. An absent directory is not an error,
        // matching the engine's idempotent reclaim.
        docker(
          "remove one local payload",
          [
            "run",
            "--rm",
            "--platform",
            platform,
            "--user",
            "999:999",
            "--network",
            "none",
            "--volume",
            `${backupsVolume()}:/backups`,
            "--entrypoint",
            "/bin/sh",
            compat.mysql_image,
            "-c",
            'cd /backups && case "$1" in (*[!A-Za-z0-9_./-]*|""|/*|*..*) echo "refusing $1" >&2; exit 1;; esac && rm -rf -- "$1" && test ! -e "$1"',
            "sh",
            relative,
          ],
          { timeoutMs: 60_000 },
        );
      },
      startExportedMysql: async (exportPath) => {
        const published = safeExportPath(exportPath);
        const name = `${project}-export-${randomBytes(3).toString("hex")}`;
        // A prepared datadir keeps the source accounts, so the client uses
        // the source root password rather than one this container never set.
        const rootPassword = mysqlRootPassword;
        // The official image entrypoint refuses a datadir it did not initialize
        // unless MYSQL_ROOT_PASSWORD is set, and then it never reaches
        // mysqld. The published export is already a prepared datadir, so the
        // process is mysqld itself with the arguments operations.md section 8
        // and p4_test.go use. The client password travels in MYSQL_PWD, which
        // docker reads from this process and does not put on a command line.
        docker(
          "start exported MySQL",
          [
            "run",
            "--detach",
            "--name",
            name,
            "--platform",
            platform,
            "--user",
            "999:999",
            "--label",
            `io.intern.e2e.export=${project}`,
            "--label",
            `${projectLabel}=${project}`,
            "--publish",
            "127.0.0.1::3306",
            "--volume",
            `${exportVolume}:${exportRoot}`,
            "--entrypoint",
            "mysqld",
            compat.mysql_image,
            `--datadir=${published}/data`,
            "--socket=/tmp/mysql.sock",
            "--pid-file=/tmp/mysqld.pid",
            "--port=3306",
            "--skip-log-bin",
            "--innodb-buffer-pool-size=64M",
          ],
          { timeoutMs: 60_000 },
        );
        exportedServers.push(name);
        const clientEnv = { MYSQL_PWD: rootPassword };
        try {
          await waitFor(
            `exported MySQL ${name}`,
            () => {
              const state = exec([
                "docker",
                "inspect",
                "--format",
                "{{.State.Status}}",
                name,
              ]).stdout.trim();
              if (state !== "running") {
                const logs = exec(["docker", "logs", "--tail", "80", name]);
                throw new Error(
                  `exported MySQL ${name} is ${state}:\n${tail(logs.stdout + logs.stderr)}`,
                );
              }
              return (
                exec(
                  [
                    "docker",
                    "exec",
                    "--env",
                    "MYSQL_PWD",
                    name,
                    "mysqladmin",
                    "--user=root",
                    "--socket=/tmp/mysql.sock",
                    "ping",
                  ],
                  { env: clientEnv, timeoutMs: 15_000 },
                ).code === 0
              );
            },
            180_000,
            2000,
          );
        } catch (error) {
          removeExported(name);
          throw error;
        }
        return {
          name,
          query: async (sqlText) => {
            const result = exec(
              [
                "docker",
                "exec",
                "-i",
                "--env",
                "MYSQL_PWD",
                name,
                ...mysqlClient,
                "--socket=/tmp/mysql.sock",
              ],
              {
                env: clientEnv,
                input: sqlText.endsWith("\n") ? sqlText : `${sqlText}\n`,
                timeoutMs: 60_000,
              },
            );
            if (result.code !== 0) {
              throw new Error(
                `exported mysql failed (exit ${result.code}): ${tail(result.stdout + result.stderr)}`,
              );
            }
            return result.stdout.replace(/\n$/, "");
          },
          stop: async () => {
            removeExported(name);
          },
        };
      },
    };
  } catch (error) {
    try {
      await cleanup();
    } catch (cleanupError) {
      throw new AggregateError(
        [error, cleanupError],
        "stack start failed and cleanup failed",
      );
    }
    throw error;
  }
}
