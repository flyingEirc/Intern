type ExecOptions = {
  cwd?: string;
  env?: Record<string, string>;
  input?: string;
  timeoutMs?: number;
};

type ExecResult = { stdout: string; stderr: string; code: number };

const debug = (message: string): void => {
  if (process.env.INTERN_E2E_STACK_DEBUG === "1") {
    process.stderr.write(
      `[e2e-stack ${new Date().toISOString()}] ${message}\n`,
    );
  }
};

function exec(command: string[], options: ExecOptions = {}): ExecResult {
  const started = Date.now();
  debug(`exec ${command.join(" ")}`);
  const result = spawnSync(command[0], command.slice(1), {
    cwd: options.cwd ?? repo,
    env: { ...process.env, ...(options.env ?? {}) },
    input: options.input,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    timeout: options.timeoutMs,
  });
  debug(`exit ${result.status ?? "error"} after ${Date.now() - started} ms`);
  if (result.error) throw result.error;
  return {
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? "",
    code: result.status ?? -1,
  };
}

function tail(text: string, limit = 4000): string {
  const trimmed = text.trim();
  return trimmed.length <= limit ? trimmed : `…${trimmed.slice(-limit)}`;
}

function must(
  label: string,
  command: string[],
  options: ExecOptions = {},
): ExecResult {
  const result = exec(command, options);
  if (result.code !== 0) {
    throw new Error(
      `${label} failed (exit ${result.code}): ${command.join(" ")}\n${tail(result.stdout + result.stderr)}`,
    );
  }
  return result;
}

function docker(
  label: string,
  args: string[],
  options: ExecOptions = {},
): ExecResult {
  return must(label, ["docker", ...args], options);
}

function randomSecret(): string {
  return `e2e-${randomBytes(18).toString("base64url")}`;
}

function git(args: string[]): string {
  return must(`git ${args.join(" ")}`, ["git", ...args], {
    cwd: repo,
  }).stdout.trim();
}

async function waitFor(
  label: string,
  probe: () => boolean | Promise<boolean>,
  timeoutMs: number,
  intervalMs = 1000,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    if (await probe()) return;
    if (Date.now() > deadline)
      throw new Error(`${label} did not become ready within ${timeoutMs} ms`);
    const { promise, resolve } = Promise.withResolvers<void>();
    setTimeout(resolve, intervalMs);
    await promise;
  }
}

function imageExists(image: string): boolean {
  return exec(["docker", "image", "inspect", image]).code === 0;
}

function requirePrerequisites(): void {
  const version = exec([
    "docker",
    "version",
    "--format",
    "{{.Server.Version}}",
  ]);
  if (version.code !== 0) {
    throw new Error(
      `docker is not available: ${tail(version.stdout + version.stderr)}`,
    );
  }
  const compose = exec(["docker", "compose", "version"]);
  if (compose.code !== 0) {
    throw new Error(
      `docker compose (v2 plugin) is not available: ${tail(compose.stdout + compose.stderr)}`,
    );
  }
}

type Compatibility = {
  mysql_image: string;
  pxb_image: string;
  platform: string;
};

function compatibility(): Compatibility {
  const entries = JSON.parse(
    readFileSync(compatFile, "utf8"),
  ) as Compatibility[];
  const entry = entries.find((candidate) => candidate.platform === platform);
  if (!entry)
    throw new Error(`internal/physical/compat.json has no ${platform} entry`);
  return entry;
}

/** The repository CLI that owns KEK generation; built on demand. */
function ensureCli(): string {
  const binary = path.join(repo, "bin/intern");
  if (existsSync(binary)) return binary;
  mkdirSync(path.dirname(binary), { recursive: true });
  // `go` is on PATH under mise; fall back to `mise exec` when the caller did not
  // activate the toolchain (mise.toml pins Go 1.27).
  const go =
    exec(["go", "version"]).code === 0 ? ["go"] : ["mise", "exec", "--", "go"];
  must("build bin/intern", [...go, "build", "-o", binary, "./app/cli"], {
    cwd: repo,
  });
  return binary;
}

/**
 * Generate a CA and one server certificate with the openssl binary inside the
 * pinned MySQL image. The certificate is valid for localhost, 127.0.0.1 and the
 * two fixture service names; the same CA is the FTPS trust anchor.
 */
function generateTls(secretsDir: string, mysqlImage: string): void {
  const script = [
    "set -eu",
    "cd /out",
    "openssl genrsa -out ca.key 2048 2>/dev/null",
    'openssl req -x509 -new -key ca.key -sha256 -days 2 -subj "/CN=Intern e2e CA" -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" -out ca.pem 2>/dev/null',
    "openssl genrsa -out server.key 2048 2>/dev/null",
    'openssl req -new -key server.key -subj "/CN=localhost" -out server.csr 2>/dev/null',
    'printf "basicConstraints=critical,CA:FALSE\\nkeyUsage=critical,digitalSignature,keyEncipherment\\nextendedKeyUsage=serverAuth\\nsubjectAltName=DNS:localhost,DNS:ftp,DNS:ftps,IP:127.0.0.1\\n" > ext.cnf',
    "openssl x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial -days 2 -sha256 -extfile ext.cnf -out intern_tls_cert 2>/dev/null",
    "cp server.key intern_tls_key",
    "cat intern_tls_cert server.key > ftps.pem",
    "rm -f ca.key server.key server.csr ca.srl ext.cnf",
    "chmod 0600 intern_tls_key",
    "chmod 0644 intern_tls_cert ca.pem ftps.pem",
  ].join("\n");
  docker(
    "generate TLS material",
    [
      "run",
      "--rm",
      "--platform",
      platform,
      "--user",
      "0:0",
      "--network",
      "none",
      "--volume",
      `${secretsDir}:/out`,
      "--entrypoint",
      "/bin/sh",
      mysqlImage,
      "-c",
      script,
    ],
    { timeoutMs: 120_000 },
  );
}
/** Copy the secrets into a named volume owned by the container user. */
function prepareSecretsVolume(
  volume: string,
  secretsDir: string,
  mysqlImage: string,
): void {
  docker("create secrets volume", ["volume", "create", volume]);
  const script = [
    "set -eu",
    "cp /in/intern_kek /in/intern_tls_cert /in/intern_tls_key /in/ca.pem /out/",
    "chown 999:999 /out/intern_kek /out/intern_tls_cert /out/intern_tls_key /out/ca.pem",
    "chmod 0600 /out/intern_kek /out/intern_tls_key",
    "chmod 0644 /out/intern_tls_cert /out/ca.pem",
  ].join("\n");
  docker("populate secrets volume", [
    "run",
    "--rm",
    "--platform",
    platform,
    "--user",
    "0:0",
    "--network",
    "none",
    "--volume",
    `${volume}:/out`,
    "--volume",
    `${secretsDir}:/in:ro`,
    "--entrypoint",
    "/bin/sh",
    mysqlImage,
    "-c",
    script,
  ]);
}

/**
 * Build a fixture image once for the host platform. The FTP servers are peers
 * on the Compose network, not binaries inside the intern image, so they do not
 * need the amd64 matrix: on an arm64 Mac they run natively while intern and
 * MySQL still run linux/amd64 under emulation. The tag carries the Dockerfile
 * digest and the platform, so neither a changed recipe nor a different host
 * architecture can reuse a stale fixture.
 */
function buildFixture(
  label: string,
  dockerfilePath: string,
  tag: string,
  context: string,
  fixturePlatform: string,
): string {
  const hash = createHash("sha256");
  for (const entry of readdirSync(context, { withFileTypes: true }).sort(
    (a, b) => a.name.localeCompare(b.name),
  )) {
    if (!entry.isFile()) continue;
    hash.update(entry.name);
    hash.update(readFileSync(path.join(context, entry.name)));
  }
  const digest = hash.digest("hex").slice(0, 12);
  const image = `${tag}-${digest}-${fixturePlatform.replace("/", "-")}`;
  if (imageExists(image)) return image;
  docker(
    label,
    [
      "build",
      "--platform",
      fixturePlatform,
      "--file",
      dockerfilePath,
      "--tag",
      image,
      context,
    ],
    { timeoutMs: 30 * 60 * 1000 },
  );
  return image;
}

function buildInternImage(
  image: string,
  sourceSha: string,
  compat: Compatibility,
): void {
  docker(
    "build intern image",
    [
      "build",
      "--platform",
      platform,
      "--file",
      dockerfile,
      "--tag",
      image,
      "--build-arg",
      `SOURCE_SHA=${sourceSha}`,
      "--build-arg",
      `MYSQL_IMAGE=${compat.mysql_image}`,
      "--build-arg",
      `PXB_IMAGE=${compat.pxb_image}`,
      repo,
    ],
    { timeoutMs: 45 * 60 * 1000 },
  );
}

function portOfComposeService(
  compose: (args: string[]) => ExecResult,
  service: string,
  privatePort: string,
): string {
  const out = compose(["port", service, privatePort]).stdout.trim();
  const match = out.match(/:(\d+)$/);
  if (!match)
    throw new Error(
      `docker compose port ${service} ${privatePort} returned ${JSON.stringify(out)}`,
    );
  return match[1];
}

function portOfContainer(name: string, privatePort: string): string {
  const out = docker(`port of ${name}`, [
    "port",
    name,
    `${privatePort}/tcp`,
  ]).stdout.trim();
  const match = out.match(/:(\d+)$/);
  if (!match)
    throw new Error(
      `docker port ${name} ${privatePort}/tcp returned ${JSON.stringify(out)}`,
    );
  return match[1];
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

/**
 * Start the stack. On any failure the partially created containers, volumes,
 * network and temporary directory are removed before the error is rethrown.
 */
export async function startStack(options: StackOptions = {}): Promise<Stack> {
  requirePrerequisites();
  const rawPlatform = exec([
    "docker",
    "info",
    "--format",
    "{{.OSType}}/{{.Architecture}}",
  ]).stdout.trim();
  const [osType, rawArch] = rawPlatform.split("/");
  const hostArch =
    { x86_64: "amd64", amd64: "amd64", aarch64: "arm64", arm64: "arm64" }[
      rawArch
    ] ?? rawArch;
  if (!osType || !hostArch) {
    throw new Error(`docker reported platform ${JSON.stringify(rawPlatform)}`);
  }
  const hostPlatform = `${osType}/${hostArch}`;
  const compat = compatibility();
  const sourceSha = git(["rev-parse", "HEAD"]);
  const dirty = git(["status", "--porcelain"]) !== "";
  const shortSha = sourceSha.slice(0, 12);
  const tagComponent = `e2e-${shortSha}${dirty ? "-dirty" : ""}`;
  const builtImage = `intern:${tagComponent}-mysql8.4`;
  const image = options.reuseImage ?? builtImage;

  const root = mkdtempSync(path.join(tmpdir(), "intern-e2e-stack-"));
  const secretsDir = path.join(root, "secrets");
  const exportDir = path.join(root, "export");
  const overrideFile = path.join(root, "override.yaml");
  const envFile = path.join(root, "stack.env");
  const plainPasswordFile = path.join(root, "ftp-password");
  const ftpsPasswordFile = path.join(root, "ftps-password");
  mkdirSync(secretsDir, { recursive: true, mode: 0o700 });
  // The export root is a host bind mount (the reference deployment publishes
  // restores on the host). OrbStack ignores chown inside the container, so the
  // test directory is world-writable to give the uid-999 process a usable export
  // root for F4 restore cases; it lives in a private mkdtemp directory.
  mkdirSync(exportDir, { recursive: true, mode: 0o777 });
  chmodSync(exportDir, 0o777);

  const project = `intern-e2e-${randomBytes(4).toString("hex")}`;
  const secretsVolume = `${project}-secrets`;
  const ftpVolume = `${project}-ftp-data`;
  const ftpsVolume = `${project}-ftps-data`;
  const noKekName = `${project}-nokek`;
  const noKekVolume = `${project}-nokek-metadata`;
  const volumes = [secretsVolume, ftpVolume, ftpsVolume, noKekVolume];

  const mysqlRootPassword = randomSecret();
  const backupPassword = randomSecret();
  const admin = { username: "e2e-admin", password: randomSecret() };
  const ftpPassword = randomSecret();
  const ftpsPassword = randomSecret();
  const noKekAdmin = { username: "e2e-nokek-admin", password: randomSecret() };

  const compose = (args: string[], execOptions: ExecOptions = {}): ExecResult =>
    exec(
      [
        "docker",
        "compose",
        "--project-name",
        project,
        "--file",
        composeFile,
        "--file",
        overrideFile,
        "--env-file",
        envFile,
        ...args,
      ],
      execOptions,
    );
  const composeMust = (
    label: string,
    args: string[],
    execOptions: ExecOptions = {},
  ): ExecResult => {
    const result = compose(args, execOptions);
    if (result.code !== 0) {
      throw new Error(
        `${label} failed (exit ${result.code}): docker compose ${args.join(" ")}\n${tail(result.stdout + result.stderr)}`,
      );
    }
    return result;
  };

  let cleaned = false;
  const cleanup = async (): Promise<void> => {
    if (cleaned) return;
    cleaned = true;
    const failures: string[] = [];
    const attempt = (
      label: string,
      action: () => ExecResult,
      absent?: RegExp,
    ): void => {
      try {
        const result = action();
        const output = result.stdout + result.stderr;
        if (result.code !== 0 && !absent?.test(output)) {
          failures.push(`${label}: ${tail(output, 800)}`);
        }
      } catch (error) {
        failures.push(`${label}: ${String(error)}`);
      }
    };
    attempt(
      "remove no-KEK container",
      () => exec(["docker", "rm", "--force", "--volumes", noKekName]),
      /no such container/i,
    );
    if (existsSync(overrideFile) && existsSync(envFile)) {
      attempt("compose down", () =>
        compose(["down", "--volumes", "--remove-orphans", "--timeout", "120"]),
      );
    }
    for (const volume of volumes) {
      attempt(
        `remove volume ${volume}`,
        () => exec(["docker", "volume", "rm", "--force", volume]),
        /no such volume|not found/i,
      );
    }
    try {
      rmSync(root, { recursive: true, force: true });
    } catch (error) {
      failures.push(`remove temporary directory: ${String(error)}`);
    }
    if (failures.length > 0) {
      throw new Error(`stack cleanup failed:\n${failures.join("\n")}`);
    }
  };

  try {
    // ------------------------------------------------------------- secrets ---
    const cli = ensureCli();
    const kekPath = path.join(secretsDir, "intern_kek");
    must("generate KEK", [cli, "keygen", "--key-file", kekPath], { cwd: repo });
    chmodSync(kekPath, 0o600);
    generateTls(secretsDir, compat.mysql_image);

    writeFileSync(plainPasswordFile, `${ftpPassword}\n${ftpPassword}\n`, {
      mode: 0o600,
    });
    writeFileSync(ftpsPasswordFile, `${ftpsPassword}\n${ftpsPassword}\n`, {
      mode: 0o600,
    });

    // ------------------------------------------------------------- fixtures ---
    const plainImage = buildFixture(
      "build plain FTP fixture",
      plainFixtureDockerfile,
      plainFixtureImage,
      path.dirname(plainFixtureDockerfile),
      hostPlatform,
    );
    const ftpsImage = buildFixture(
      "build FTPS fixture",
      ftpsFixtureDockerfile,
      ftpsFixtureImage,
      path.dirname(ftpsFixtureDockerfile),
      hostPlatform,
    );

    // ---------------------------------------------------------------- image ---
    if (options.reuseImage) {
      if (!imageExists(options.reuseImage)) {
        throw new Error(
          `reuseImage ${options.reuseImage} does not exist locally`,
        );
      }
      const inspected = docker("inspect reuseImage", [
        "image",
        "inspect",
        "--format",
        "{{.Os}}/{{.Architecture}}",
        options.reuseImage,
      ]).stdout.trim();
      if (inspected !== platform) {
        throw new Error(
          `reuseImage ${options.reuseImage} is ${inspected}, want ${platform}`,
        );
      }
    } else {
      buildInternImage(builtImage, sourceSha, compat);
    }

    // ---------------------------------------------------------------- volumes ---
    prepareSecretsVolume(secretsVolume, secretsDir, compat.mysql_image);
    docker("create plain FTP data volume", ["volume", "create", ftpVolume]);
    docker("create FTPS data volume", ["volume", "create", ftpsVolume]);
    // The fixtures chroot each account to its home, so the repository base path
    // is relative to that home. Pre-create it as the FTP user would.
    docker("prepare FTP data volumes", [
      "run",
      "--rm",
      "--platform",
      hostPlatform,
      "--user",
      "0:0",
      "--network",
      "none",
      "--volume",
      `${ftpVolume}:/ftp`,
      "--volume",
      `${ftpsVolume}:/ftps`,
      "--entrypoint",
      "/bin/sh",
      alpineImage,
      "-c",
      "mkdir -p /ftp/normal/backups /ftps/normal/backups && chown -R 1000:1000 /ftp /ftps",
    ]);

    // --------------------------------------------------------------- override ---
    const override = [
      "# Generated by app/web/frontend/e2e/stack.ts. Test-only Compose override:",
      "# it points the service at the uid-999 secrets volume, adds the FTP fixtures",
      "# and sizes MySQL for a laptop. It declares no deployment semantics.",
      "services:",
      "  mysql:",
      `    platform: ${platform}`,
      "    command:",
      "      - --innodb-buffer-pool-size=64M",
      "      - --innodb-redo-log-capacity=33554432",
      "  intern:",
      `    platform: ${platform}`,
      `    image: ${yamlString(image)}`,
      "    # OrbStack's cgroup v2 layout has no io.weight; the reference file's",
      "    # blkio_config would make container creation fail on a Mac. This is a",
      "    # test-only host adaptation, not a deployment change.",
      "    blkio_config: !reset null",
      "    environment:",
      "      INTERN_KEK_FILE: /run/intern-secrets/intern_kek",
      "      INTERN_TLS_CERT_FILE: /run/intern-secrets/intern_tls_cert",
      "      INTERN_TLS_KEY_FILE: /run/intern-secrets/intern_tls_key",
      "    volumes:",
      '      - "intern-secrets:/run/intern-secrets:ro"',
      "  ftp:",
      `    platform: ${hostPlatform}`,
      `    image: ${yamlString(plainImage)}`,
      '    entrypoint: ["/bin/sh", "-c", "cp /fixture/password /run/s1-password && exec /usr/local/bin/ftp-fixture"]',
      "    volumes:",
      `      - ${yamlString(`${plainPasswordFile}:/fixture/password:ro`)}`,
      '      - "ftp-data:/data"',
      "    healthcheck:",
      '      test: ["CMD-SHELL", "nc -z 127.0.0.1 2121"]',
      "      interval: 2s",
      "      timeout: 2s",
      "      retries: 30",
      "      start_period: 5s",
      "  ftps:",
      `    platform: ${hostPlatform}`,
      `    image: ${yamlString(ftpsImage)}`,
      '    entrypoint: ["/bin/sh", "-c", "cp /fixture/password /run/ftp-password && exec /usr/local/bin/ftps-fixture"]',
      "    volumes:",
      `      - ${yamlString(`${ftpsPasswordFile}:/fixture/password:ro`)}`,
      `      - ${yamlString(`${path.join(secretsDir, "ftps.pem")}:/run/tls/ftps.pem:ro`)}`,
      '      - "ftps-data:/data"',
      "    healthcheck:",
      '      test: ["CMD-SHELL", "nc -z 127.0.0.1 2121 && nc -z 127.0.0.1 990"]',
      "      interval: 2s",
      "      timeout: 2s",
      "      retries: 30",
      "      start_period: 5s",
      "volumes:",
      "  intern-secrets:",
      `    name: ${yamlString(secretsVolume)}`,
      "  ftp-data:",
      `    name: ${yamlString(ftpVolume)}`,
      "  ftps-data:",
      `    name: ${yamlString(ftpsVolume)}`,
      "",
    ].join("\n");
    writeFileSync(overrideFile, override, { mode: 0o600 });

    const env = [
      `MYSQL_ROOT_PASSWORD=${mysqlRootPassword}`,
      `INTERN_MYSQL_IMAGE=${compat.mysql_image}`,
      `INTERN_PXB_IMAGE=${compat.pxb_image}`,
      `INTERN_VERSION=${tagComponent}`,
      `INTERN_SOURCE_SHA=${sourceSha}`,
      "INTERN_HOST_PORT=0",
      `INTERN_KEK_FILE_HOST=${path.join(secretsDir, "intern_kek")}`,
      `INTERN_TLS_CERT_HOST=${path.join(secretsDir, "intern_tls_cert")}`,
      `INTERN_TLS_KEY_HOST=${path.join(secretsDir, "intern_tls_key")}`,
      `INTERN_EXPORT_HOST_DIR=${exportDir}`,
      "INTERN_MIN_WORK_BYTES=268435456",
      "INTERN_MIN_BACKUP_BYTES=268435456",
      "INTERN_LOG_LEVEL=info",
      "COMPOSE_PROGRESS=quiet",
      "",
    ].join("\n");
    writeFileSync(envFile, env, { mode: 0o600 });

    // ----------------------------------------------------------------- start ---
    // `up --detach` returns after the containers are created. Health is then
    // read from the containers' own healthchecks, so a failure names the
    // service and includes its logs instead of a generic Compose timeout.
    composeMust("docker compose up", ["up", "--detach"], {
      timeoutMs: 10 * 60 * 1000,
    });
    const serviceContainer = (service: string): string => {
      const ids = composeMust(`container of ${service}`, ["ps", "-q", service])
        .stdout.trim()
        .split("\n")
        .filter(Boolean);
      if (ids.length !== 1)
        throw new Error(
          `service ${service} has ${ids.length} containers, want 1`,
        );
      return ids[0];
    };
    const serviceHealth = async (
      service: string,
      timeoutMs: number,
    ): Promise<void> => {
      const id = serviceContainer(service);
      await waitFor(
        `${service} health`,
        () => {
          const out = exec([
            "docker",
            "inspect",
            "--format",
            "{{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}",
            id,
          ]).stdout.trim();
          const [state, health] = out.split(" ");
          if (state !== "running") {
            const logs = compose(["logs", "--tail", "60", service]);
            throw new Error(
              `${service} is ${state}:\n${tail(logs.stdout + logs.stderr)}`,
            );
          }
          return health === "healthy";
        },
        timeoutMs,
      );
    };
    await Promise.all([
      serviceHealth("mysql", 300_000),
      serviceHealth("ftp", 120_000),
      serviceHealth("ftps", 120_000),
      serviceHealth("intern", 300_000),
    ]);
    const port = portOfComposeService(compose, "intern", "8443");
    const origin = `https://127.0.0.1:${port}`;

    // `migrate status` is the documented readiness entry point; the service
    // healthcheck only proves the process answers /healthz.
    await waitFor(
      "intern migrate status",
      () =>
        compose(["exec", "-T", "intern", "intern-web", "migrate", "status"])
          .code === 0,
      120_000,
    );

    // --------------------------------------------------------- backup account ---
    const sql = [
      `CREATE USER IF NOT EXISTS '${backupUser}'@'localhost' IDENTIFIED BY '${backupPassword}';`,
      `GRANT BACKUP_ADMIN, PROCESS, RELOAD, LOCK TABLES, REPLICATION CLIENT ON *.* TO '${backupUser}'@'localhost';`,
      `GRANT SELECT ON performance_schema.log_status TO '${backupUser}'@'localhost';`,
      `GRANT SELECT ON performance_schema.keyring_component_status TO '${backupUser}'@'localhost';`,
      `GRANT SELECT ON performance_schema.replication_group_members TO '${backupUser}'@'localhost';`,
      "",
    ].join("\n");
    composeMust(
      "create backup account",
      [
        "exec",
        "-T",
        "mysql",
        "sh",
        "-c",
        'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" exec mysql -uroot',
      ],
      { input: sql },
    );

    // ------------------------------------------------------------- first admin ---
    composeMust(
      "create first admin",
      [
        "exec",
        "-T",
        "intern",
        "intern-web",
        "user",
        "create-admin",
        "--username",
        admin.username,
        "--password-stdin",
      ],
      { input: `${admin.password}\n` },
    );

    // ------------------------------------------------------- KEK-less instance ---
    docker("create no-KEK metadata volume", ["volume", "create", noKekVolume]);
    docker("start no-KEK intern", [
      "run",
      "--detach",
      "--name",
      noKekName,
      "--platform",
      platform,
      "--user",
      "999:999",
      "--label",
      `io.intern.e2e.project=${project}`,
      "--publish",
      "127.0.0.1::8443",
      "--env",
      "INTERN_LISTEN=0.0.0.0:8443",
      "--env",
      "INTERN_METADATA_DIR=/var/lib/intern/metadata",
      "--env",
      "INTERN_TLS_CERT_FILE=/run/intern-secrets/intern_tls_cert",
      "--env",
      "INTERN_TLS_KEY_FILE=/run/intern-secrets/intern_tls_key",
      "--env",
      "INTERN_LOG_LEVEL=info",
      "--volume",
      `${noKekVolume}:/var/lib/intern/metadata`,
      "--volume",
      `${secretsVolume}:/run/intern-secrets:ro`,
      image,
    ]);
    await waitFor(
      "no-KEK intern healthcheck",
      () =>
        exec(["docker", "exec", noKekName, "intern-web", "healthcheck"])
          .code === 0,
      180_000,
    );
    docker(
      "create no-KEK admin",
      [
        "exec",
        "-i",
        noKekName,
        "intern-web",
        "user",
        "create-admin",
        "--username",
        noKekAdmin.username,
        "--password-stdin",
      ],
      { input: `${noKekAdmin.password}\n` },
    );
    const noKekOrigin = `https://127.0.0.1:${portOfContainer(noKekName, "8443")}`;

    const caBundlePem = readFileSync(path.join(secretsDir, "ca.pem"), "utf8");

    return {
      origin,
      admin,
      mysql: {
        socket: mysqlSocket,
        datadir: mysqlDataDir,
        username: backupUser,
        password: backupPassword,
      },
      ftp: {
        host: "ftp",
        port: 2121,
        username: "normal",
        password: ftpPassword,
        basePath: "/backups",
      },
      ftps: {
        host: "ftps",
        port: 2121,
        username: "normal",
        password: ftpsPassword,
        basePath: "/backups",
        tlsMode: "explicit",
        caBundlePem,
      },
      localRepositoryRoot,
      noKek: { origin: noKekOrigin, admin: noKekAdmin },
      setFtp: (state) => {
        // Detaching the running container from the Compose network is a real
        // outage that keeps the server's state: restarting the fixture would
        // lose its one-shot password file, so the service is not stopped.
        const container = composeMust("find the plain FTP container", [
          "ps",
          "--quiet",
          "ftp",
        ]).stdout.trim();
        const network = `${project}_default`;
        docker(
          state === "down"
            ? "detach the plain FTP server"
            : "reattach the plain FTP server",
          state === "down"
            ? ["network", "disconnect", network, container]
            : ["network", "connect", "--alias", "ftp", network, container],
        );
      },
      stop: cleanup,
    };
  } catch (error) {
    try {
      await cleanup();
    } catch (cleanupError) {
      throw new AggregateError(
        [error, cleanupError],
        "stack start failed and cleanup failed",
      );
    }
    throw error;
  }
}
