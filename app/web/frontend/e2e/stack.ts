// Real-component end-to-end stack for the Web frontend stages F2–F4.
//
// The stack is the repository's own reference deployment
// (app/web/deploy/compose.yaml, app/web/deploy/Dockerfile) driven by the real
// `docker compose` CLI, plus two real FTP servers on the same Compose network:
//
//   * the pinned Pure-FTPd 1.0.54 plain fixture from app/web/integration
//     (ftp.Dockerfile), built unchanged; the override only copies the injected
//     password into the container's writable /run so the fixture's own
//     entrypoint can delete it exactly as it does under testcontainers;
//   * a sibling FTPS fixture built from the same pinned Alpine digest, the same
//     Pure-FTPd 1.0.54 tarball and the same configure flags (e2e/fixtures),
//     serving an explicit-TLS listener and the IMPLICIT_TLS build.
//
// Nothing is simulated: the API, the metadata SQLite file, MySQL 8.4.11,
// Percona XtraBackup 8.4.0-7 and the FTP servers are the real binaries named by
// internal/physical/compat.json.
//
// Prerequisites
// -------------
// * Docker Engine with the Compose v2 plugin, including the `!reset` YAML tag
//   used by the generated override (verified with Compose v5.5.0).
// * `git` (the image tag records the commit).
// * Go 1.27 through mise (`mise exec -- go version`) only when bin/intern is
//   missing: the KEK keyset is generated by the repository CLI (`intern keygen`),
//   exactly as docs/guide/operations.md section 5 describes. TLS material is
//   generated with the openssl binary already present in the pinned MySQL image,
//   so no host certificate tool is needed.
// * About 6 GB of free Docker disk for the amd64 image, the pinned MySQL/PXB
//   images and the two FTP fixtures.
//
// Platform and emulation caveat
// -----------------------------
// The intern image and the MySQL/PXB tools are linux/amd64 (compat.json has no
// other entry), so those are built and run with `--platform linux/amd64`. On an
// arm64 Mac (OrbStack/Colima/Docker Desktop) that means CPU emulation: results
// from such a run are development evidence only. Binding acceptance stays on a
// native linux/amd64 host (docs/guide/quality.md, Web roadmap section 13).
// Everything observable through the API is still the real software:
// `@@version_compile_machine` is x86_64 and the preflight compatibility check
// sees linux/amd64.
//
// The two FTP fixtures are peers on the Compose network, not binaries inside the
// intern image, so they are built for the Docker daemon's own platform. That is
// not a shortcut around the matrix: the pinned Pure-FTPd 1.0.54 source and build
// recipe are unchanged. It is required on this arm64 dev host, where the amd64
// pure-ftpd build starts but every session dies with Rosetta mmap errors before
// the FTP greeting. On a native linux/amd64 host the fixtures are amd64 too.
//
// macOS bind mounts and file secrets
// ----------------------------------
// Compose file secrets are ordinary bind mounts, and `intern-web serve` requires
// the KEK to be a regular file owned by the container uid with mode 0600
// (docs/guide/operations.md section 5). OrbStack presents bind-mounted host
// files as root-owned regardless of the host owner and ignores chown inside the
// container, so a bind-mounted KEK can never satisfy uid 999. The stack therefore
// copies the KEK and TLS files into a named volume with a one-shot helper
// container, gives them uid 999 and the documented modes, and points the service
// at that volume through the generated Compose override. The repository compose
// file itself is not modified.
//
// Lifecycle
// ---------
// startStack() builds the image (or reuses one), starts the stack, waits for the
// healthchecks, creates the 'intern_bkp'@'localhost' backup account with the
// grants from the control-plane roadmap section 3.2, creates the first admin
// through `intern-web user create-admin --password-stdin`, and also starts a
// second intern container without a KEK (own metadata volume, same image) for
// the 503 "not configured" acceptance cases. stop() removes every container,
// volume, network and temporary file the call created; images stay in the local
// cache because they are reused across runs.
//
// Measured on an Apple M-series Mac (OrbStack, linux/amd64 emulation) on
// 2026-11-06; native linux/amd64 is faster:
//   * first image build (frontend + Go + licenses): several minutes, and it
//     dominates the first start. A repeated build with the BuildKit cache still
//     takes about 2 minutes here (the 1.2 GB image is re-exported).
//   * startStack() with the image and fixtures cached: 133–145 s, of which
//     about 120 s is the cached rebuild and 11 s is `docker compose up`
//     including MySQL 8.4.11 and the intern healthcheck.
//   * source preflight against the real MySQL/PXB pair: 0.3 s once warm.
//   * probes: local repository 6–9 ms, plain FTP 0.16–0.18 s, explicit FTPS
//     0.87–0.89 s.
//   * stop(): 1.7–2.4 s for the four Compose services, the KEK-less container,
//     the volumes, the network and the temporary directory.
// Subsequent starts reuse the built image and the fixture images.

