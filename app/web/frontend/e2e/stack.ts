type ExecOptions = {
  cwd?: string;
  env?: Record<string, string>;
  input?: string;
  timeoutMs?: number;
};

type ExecResult = { stdout: string; stderr: string; code: number };

const debug = (message: string): void => {
  if (process.env.INTERN_E2E_STACK_DEBUG === "1") {
    process.stderr.write(
      `[e2e-stack ${new Date().toISOString()}] ${message}\n`,
    );
  }
};

function exec(command: string[], options: ExecOptions = {}): ExecResult {
  const started = Date.now();
  debug(`exec ${command.join(" ")}`);
  const result = spawnSync(command[0], command.slice(1), {
    cwd: options.cwd ?? repo,
    env: { ...process.env, ...(options.env ?? {}) },
    input: options.input,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
    timeout: options.timeoutMs,
  });
  debug(`exit ${result.status ?? "error"} after ${Date.now() - started} ms`);
  if (result.error) throw result.error;
  return {
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? "",
    code: result.status ?? -1,
  };
}

function tail(text: string, limit = 4000): string {
  const trimmed = text.trim();
  return trimmed.length <= limit ? trimmed : `…${trimmed.slice(-limit)}`;
}

function must(
  label: string,
  command: string[],
  options: ExecOptions = {},
): ExecResult {
  const result = exec(command, options);
  if (result.code !== 0) {
    throw new Error(
      `${label} failed (exit ${result.code}): ${command.join(" ")}\n${tail(result.stdout + result.stderr)}`,
    );
  }
  return result;
}

function docker(
  label: string,
  args: string[],
  options: ExecOptions = {},
): ExecResult {
  return must(label, ["docker", ...args], options);
}

function randomSecret(): string {
  return `e2e-${randomBytes(18).toString("base64url")}`;
}

function git(args: string[]): string {
  return must(`git ${args.join(" ")}`, ["git", ...args], {
    cwd: repo,
  }).stdout.trim();
}

async function waitFor(
  label: string,
  probe: () => boolean | Promise<boolean>,
  timeoutMs: number,
  intervalMs = 1000,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    if (await probe()) return;
    if (Date.now() > deadline)
      throw new Error(`${label} did not become ready within ${timeoutMs} ms`);
    const { promise, resolve } = Promise.withResolvers<void>();
    setTimeout(resolve, intervalMs);
    await promise;
  }
}

function imageExists(image: string): boolean {
  return exec(["docker", "image", "inspect", image]).code === 0;
}

function requirePrerequisites(): void {
  const version = exec([
    "docker",
    "version",
    "--format",
    "{{.Server.Version}}",
  ]);
  if (version.code !== 0) {
    throw new Error(
      `docker is not available: ${tail(version.stdout + version.stderr)}`,
    );
  }
  const compose = exec(["docker", "compose", "version"]);
  if (compose.code !== 0) {
    throw new Error(
      `docker compose (v2 plugin) is not available: ${tail(compose.stdout + compose.stderr)}`,
    );
  }
}

type Compatibility = {
  mysql_image: string;
  pxb_image: string;
  platform: string;
};

function compatibility(): Compatibility {
  const entries = JSON.parse(
    readFileSync(compatFile, "utf8"),
  ) as Compatibility[];
  const entry = entries.find((candidate) => candidate.platform === platform);
  if (!entry)
    throw new Error(`internal/physical/compat.json has no ${platform} entry`);
  return entry;
}

/** The repository CLI that owns KEK generation; built on demand. */
function ensureCli(): string {
  const binary = path.join(repo, "bin/intern");
  if (existsSync(binary)) return binary;
  mkdirSync(path.dirname(binary), { recursive: true });
  // `go` is on PATH under mise; fall back to `mise exec` when the caller did not
  // activate the toolchain (mise.toml pins Go 1.27).
  const go =
    exec(["go", "version"]).code === 0 ? ["go"] : ["mise", "exec", "--", "go"];
  must("build bin/intern", [...go, "build", "-o", binary, "./app/cli"], {
    cwd: repo,
  });
  return binary;
}

/**
 * Generate a CA and one server certificate with the openssl binary inside the
 * pinned MySQL image. The certificate is valid for localhost, 127.0.0.1 and the
 * two fixture service names; the same CA is the FTPS trust anchor.
 */
function generateTls(secretsDir: string, mysqlImage: string): void {
  const script = [
    "set -eu",
    "cd /out",
    "openssl genrsa -out ca.key 2048 2>/dev/null",
    'openssl req -x509 -new -key ca.key -sha256 -days 2 -subj "/CN=Intern e2e CA" -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" -out ca.pem 2>/dev/null',
    "openssl genrsa -out server.key 2048 2>/dev/null",
    'openssl req -new -key server.key -subj "/CN=localhost" -out server.csr 2>/dev/null',
    'printf "basicConstraints=critical,CA:FALSE\\nkeyUsage=critical,digitalSignature,keyEncipherment\\nextendedKeyUsage=serverAuth\\nsubjectAltName=DNS:localhost,DNS:ftp,DNS:ftps,IP:127.0.0.1\\n" > ext.cnf',
    "openssl x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial -days 2 -sha256 -extfile ext.cnf -out intern_tls_cert 2>/dev/null",
    "cp server.key intern_tls_key",
    "cat intern_tls_cert server.key > ftps.pem",
    "rm -f ca.key server.key server.csr ca.srl ext.cnf",
    "chmod 0600 intern_tls_key",
    "chmod 0644 intern_tls_cert ca.pem ftps.pem",
  ].join("\n");
  docker(
    "generate TLS material",
    [
      "run",
      "--rm",
      "--platform",
      platform,
      "--user",
      "0:0",
      "--network",
      "none",
      "--volume",
      `${secretsDir}:/out`,
      "--entrypoint",
      "/bin/sh",
      mysqlImage,
      "-c",
      script,
    ],
    { timeoutMs: 120_000 },
  );
}
