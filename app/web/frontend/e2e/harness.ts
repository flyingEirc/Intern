// Shared driver pieces for the end-to-end scripts: an agent-browser session
// bound to one evidence directory, a TLS-tolerant API client, a native
// `bin/intern-web` for the suites that need no external component, and the
// run manifest. Nothing here asserts product behavior; the scripts do.
import { type ChildProcess, spawn, spawnSync } from "node:child_process";
import { once } from "node:events";
import {
  chmodSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

export const repo = path.resolve(import.meta.dir, "../../../..");

export type Step = {
  id: string;
  acceptance: string;
  description: string;
  screenshot?: string;
};

export function expect(condition: boolean, message: string): void {
  if (!condition) {
    throw new Error(`e2e: ${message}`);
  }
}

/** The commit under test, whether the tree was dirty, and parsed CLI flags. */
export function runContext(suite: string) {
  const args = process.argv.slice(2);
  const commit =
    spawnSync("git", ["rev-parse", "--short=12", "HEAD"], {
      cwd: repo,
      encoding: "utf8",
    }).stdout.trim() || "unknown";
  const dirty =
    spawnSync("git", ["status", "--porcelain"], {
      cwd: repo,
      encoding: "utf8",
    }).stdout.trim() !== "";
  const flag = (name: string) => {
    const index = args.indexOf(name);
    return index >= 0 ? args[index + 1] : undefined;
  };
  const evidenceFlag = flag("--evidence");
  const evidence = evidenceFlag
    ? path.resolve(evidenceFlag)
    : path.join(repo, `.cache/e2e-${suite}`, commit);
  mkdirSync(evidence, { recursive: true });
  return {
    commit,
    dirty,
    evidence,
    headed: args.includes("--headed"),
    image: flag("--image"),
  };
}

/** One agent-browser session; every command and screenshot goes through it. */
export class Browser {
  readonly steps: Step[] = [];

  constructor(
    private readonly session: string,
    private readonly evidence: string,
    private readonly headed: boolean,
  ) {}

  ab(...command: string[]): string {
    const result = spawnSync(
      "agent-browser",
      [
        "--session",
        this.session,
        ...(this.headed ? ["--headed"] : []),
        ...command,
      ],
      { encoding: "utf8", timeout: 900_000 },
    );
    if (result.status !== 0) {
      throw new Error(
        `agent-browser ${command.join(" ")} failed: ${(result.stderr || result.stdout).trim()}\n${this.diagnostics()}`,
      );
    }
    return result.stdout.trim();
  }

  /** Where the page was and what it said, for a failed command's error. */
  private diagnostics(): string {
    const read = (...command: string[]) =>
      spawnSync("agent-browser", ["--session", this.session, ...command], {
        encoding: "utf8",
        timeout: 30_000,
      }).stdout.trim();
    return `page ${read("get", "url")}: ${read("get", "text", "body").slice(0, 1500)}`;
  }

  /** The stack's certificate is generated by this run; only its errors are ignored. */
  open(url: string): void {
    this.ab("--ignore-https-errors", "open", url);
  }

  waitText(text: string, timeoutMs?: number): void {
    this.ab(
      "wait",
      "--text",
      text,
      ...(timeoutMs === undefined ? [] : ["--timeout", String(timeoutMs)]),
    );
  }

  fill(label: string, value: string): void {
    this.ab("find", "label", label, "fill", value);
  }

  click(name: string, role = "button"): void {
    this.ab("find", "role", role, "click", "--name", name);
  }

  text(): string {
    return this.ab("get", "text", "body");
  }

  url(): string {
    return this.ab("get", "url");
  }

  shot(name: string): string {
    const file = path.join(this.evidence, `${name}.png`);
    this.ab(
      "wait",
      "--fn",
      "document.getAnimations().every((a) => a.playState !== 'running')",
    );
    // Full page: the evidence of a section below the fold must be in the image.
    this.ab("screenshot", "--full", file);
    return path.basename(file);
  }

  record(step: Step): void {
    this.steps.push(step);
    console.log(`pass ${step.id} (${step.acceptance}): ${step.description}`);
  }

  signIn(origin: string, username: string, password: string): void {
    this.open(`${origin}/login`);
    this.waitText("使用 Intern 账号登录控制台");
    this.fill("用户名", username);
    this.fill("密码", password);
    this.click("登录");
    this.waitText("有效权限");
  }

  /** The login page sends a signed-in visitor on, so switch users through logout. */
  signOut(): void {
    this.ab("find", "role", "button", "click", "--name", "账户菜单");
    this.ab("wait", "--text", "退出登录");
    this.ab("find", "role", "menuitem", "click", "--name", "退出登录");
    this.ab("wait", "--url", "**/login**");
    // The form renders after hydration, inside a Suspense boundary.
    this.waitText("使用 Intern 账号登录控制台");
  }

  /** Page errors and CSP violations fail the run. */
  assertCleanConsole(): void {
    const errors = this.ab("errors");
    expect(errors === "", `page errors: ${errors}`);
    const output = this.ab("console");
    expect(
      !/Content Security Policy|Refused to/i.test(output),
      `CSP violations: ${output}`,
    );
  }

  close(): void {
    spawnSync("agent-browser", ["--session", this.session, "close"], {
      encoding: "utf8",
    });
  }

  /** Writes this session's steps, plus those of `others` sharing the run, in id order. */
  writeManifest(commit: string, dirty: boolean, others: Browser[] = []): void {
    const steps = [this, ...others]
      .flatMap((browser) => browser.steps)
      .sort((a, b) => a.id.localeCompare(b.id));
    writeFileSync(
      path.join(this.evidence, "manifest.json"),
      `${JSON.stringify({ commit, dirty, steps }, null, 2)}\n`,
    );
  }
}

/** One HTTP call against the stack; TLS verification is disabled for this run's own certificate. */
export type ApiClient = (
  method: string,
  route: string,
  cookie: string | undefined,
  body?: unknown,
  headers?: Record<string, string>,
) => Promise<{ status: number; json: unknown; cookie?: string }>;

export function makeApi(origin: string): ApiClient {
  return async (method, route, cookie, body, headers = {}) => {
    const response = await fetch(`${origin}${route}`, {
      method,
      headers: {
        ...(cookie === undefined ? {} : { Cookie: cookie }),
        ...(body === undefined ? {} : { "Content-Type": "application/json" }),
        ...headers,
      },
      body: body === undefined ? undefined : JSON.stringify(body),
      tls: { rejectUnauthorized: false },
    } as RequestInit);
    const text = await response.text();
    const sessionCookie = response.headers
      .getSetCookie()
      .find((value) => value.startsWith("intern_session="))
      ?.split(";")[0];
    return {
      status: response.status,
      json: text === "" ? undefined : JSON.parse(text),
      cookie: sessionCookie,
    };
  };
}

export async function apiLogin(
  api: ApiClient,
  username: string,
  password: string,
): Promise<string> {
  const result = await api("POST", "/api/v1/auth/login", undefined, {
    username,
    password,
  });
  expect(
    result.status === 200 && result.cookie !== undefined,
    `API login ${username} = ${result.status}`,
  );
  return result.cookie as string;
}

export async function createUser(
  api: ApiClient,
  adminCookie: string,
  username: string,
  password: string,
  role: "admin" | "operator" | "viewer",
): Promise<string> {
  const result = await api("POST", "/api/v1/users", adminCookie, {
    username,
    password,
    role,
  });
  expect(
    result.status === 201,
    `create ${role} = ${result.status} ${JSON.stringify(result.json)}`,
  );
  return (result.json as { id: string }).id;
}

export const randomPassword = (prefix: string) =>
  `${prefix}-${Math.random().toString(36).slice(2, 12)}${Math.random().toString(36).slice(2, 6)}`;

/** Polls fn until it returns a value, or fails with the last observation. */
export async function until<T>(
  what: string,
  timeoutMs: number,
  fn: () => Promise<T | undefined>,
): Promise<T> {
  const deadline = Date.now() + timeoutMs;
  for (;;) {
    const value = await fn();
    if (value !== undefined) {
      return value;
    }
    if (Date.now() > deadline) {
      throw new Error(
        `e2e: timed out after ${timeoutMs} ms waiting for ${what}`,
      );
    }
    await Bun.sleep(2000);
  }
}

/**
 * Runs stop() when the run is interrupted (Ctrl-C, a job cancel), so an
 * aborted run does not leave containers, volumes and networks behind.
 */
export function stopOnSignal(stop: () => Promise<void>): void {
  for (const signal of ["SIGINT", "SIGTERM"] as const) {
    process.once(signal, () => {
      void stop().finally(() => process.exit(130));
    });
  }
}

/**
 * One native `bin/intern-web` on loopback HTTP: migrated metadata, one
 * administrator created through `--password-stdin`, and the process itself.
 * `stop()` kills the process and removes the metadata directory.
 */
export async function startNative(options: {
  admin: { username: string; password: string };
}): Promise<{
  origin: string;
  work: string;
  stop: () => Promise<void>;
}> {
  const binary = path.join(repo, "bin/intern-web");
  const work = mkdtempSync(path.join(tmpdir(), "intern-web-e2e-"));
  const metadata = path.join(work, "metadata");
  mkdirSync(metadata, { mode: 0o700 });
  chmodSync(metadata, 0o700);
  const port = 20_000 + Math.floor(Math.random() * 20_000);
  const origin = `http://127.0.0.1:${port}`;

  const command = (args: string[], input?: string) => {
    const result = spawnSync(binary, args, { input, encoding: "utf8" });
    if (result.status !== 0) {
      rmSync(work, { recursive: true, force: true });
      throw new Error(
        `e2e: intern-web ${args.slice(0, 2).join(" ")} exited ${result.status}: ${result.stderr.trim()}`,
      );
    }
  };
  command(["migrate", "up", "--metadata-dir", metadata]);
  command(
    [
      "user",
      "create-admin",
      "--username",
      options.admin.username,
      "--metadata-dir",
      metadata,
      "--password-stdin",
    ],
    `${options.admin.password}\n`,
  );

  const server: ChildProcess = spawn(
    binary,
    ["serve", "--metadata-dir", metadata, "--listen", `127.0.0.1:${port}`],
    { stdio: ["ignore", "ignore", "pipe"] },
  );
  let serverLog = "";
  server.stderr?.on("data", (chunk: Buffer) => {
    serverLog += chunk.toString();
  });
  const deadline = Date.now() + 20_000;
  let ready = false;
  while (Date.now() < deadline) {
    try {
      if ((await fetch(`${origin}/readyz`)).status === 200) {
        ready = true;
        break;
      }
    } catch {
      // Not listening yet.
    }
    await Bun.sleep(100);
  }
  if (!ready) {
    server.kill("SIGTERM");
    rmSync(work, { recursive: true, force: true });
    throw new Error(`e2e: intern-web did not become ready:\n${serverLog}`);
  }

  return {
    origin,
    work,
    stop: async () => {
      server.kill("SIGTERM");
      if (server.exitCode === null) {
        await once(server, "exit");
      }
      rmSync(work, { recursive: true, force: true });
    },
  };
}
